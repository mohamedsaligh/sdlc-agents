#!/usr/bin/env python3
"""Generate harness-specific agent files from the canonical definitions in agents/.

  agents/<name>.md  --->  .github/agents/<name>.agent.md   (VS Code Copilot custom agent)
                    --->  .claude/agents/<name>.md         (Claude Code sub-agent)

Only agents/*.md is edited by humans. Run this after every change:
  python scripts/sync-agents.py          # write
  python scripts/sync-agents.py --check  # exit 1 if generated files are stale (for CI)
Standard library only.
"""
import argparse
import os
import re
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(REPO_ROOT, "agents")
TARGETS = {
    "copilot": os.path.join(REPO_ROOT, ".github", "agents"),
    "claude": os.path.join(REPO_ROOT, ".claude", "agents"),
}
BANNER = "<!-- GENERATED by scripts/sync-agents.py from agents/{src}. Do not edit; edit the source and re-run. -->\n"


def split_front_matter(text):
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if not m:
        raise SystemExit("canonical agent file must start with YAML front matter (--- name/description ---)")
    meta = {}
    for line in m.group(1).splitlines():
        k, _, v = line.partition(":")
        meta[k.strip()] = v.strip()
    return meta, m.group(2)


def render(harness, meta, body, src_name):
    name = meta["name"]
    desc = meta["description"].replace('"', "'")
    preamble = (
        "Before doing anything, read `AGENTS.md` at the repository root and follow it. "
        "It defines run folders, execution ids, tool rules and output templates for this agent.\n\n"
    )
    if harness == "copilot":
        fm = f"---\nname: {name}\ndescription: \"{desc}\"\n---\n"
    else:  # claude
        fm = f"---\nname: {name}\ndescription: \"{desc}\"\n---\n"
    return fm + BANNER.format(src=src_name) + "\n" + preamble + body.lstrip()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="verify generated files are up to date")
    args = ap.parse_args()

    sources = sorted(f for f in os.listdir(SRC) if f.endswith(".md"))
    if not sources:
        raise SystemExit("no agents/*.md found")
    stale = []
    for src_name in sources:
        with open(os.path.join(SRC, src_name), encoding="utf-8") as fh:
            meta, body = split_front_matter(fh.read())
        stem = os.path.splitext(src_name)[0]
        outputs = {
            "copilot": os.path.join(TARGETS["copilot"], f"{stem}.agent.md"),
            "claude": os.path.join(TARGETS["claude"], f"{stem}.md"),
        }
        for harness, path in outputs.items():
            content = render(harness, meta, body, src_name)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            if args.check:
                try:
                    with open(path, encoding="utf-8") as fh:
                        if fh.read() != content:
                            stale.append(path)
                except FileNotFoundError:
                    stale.append(path)
            else:
                with open(path, "w", encoding="utf-8", newline="\n") as fh:
                    fh.write(content)
                print("wrote", os.path.relpath(path, REPO_ROOT))
    if args.check:
        if stale:
            print("STALE generated agent files (run: python scripts/sync-agents.py):")
            for p in stale:
                print("  ", os.path.relpath(p, REPO_ROOT))
            return 1
        print("generated agent files are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
